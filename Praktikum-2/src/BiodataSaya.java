public class BiodataSaya {
    public static void main(String[] args) {
        //C menyimpan angka
        double C = 16.00;
        //konversi suhu celcius ke fahrenheit
        double F = (C * 9/5 + 32);
        //menampilkan nilai yang akan di konversikan
        System.out.println(C + " derajat celcius = " + F + " derajat fahrenheit");
    }
}
